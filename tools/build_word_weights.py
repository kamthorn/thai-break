#!/usr/bin/env python3
"""
tools/build_word_weights.py
Build data/word-weights.tsv: unigram weights for the most frequent words of the
base dictionary, counted on the Prachathai-67k news corpus (Apache-2.0).

Usage:
  python3 tools/build_word_weights.py [--top 3000] [--exponent 0.5] \\
      [--cache-dir ~/.cache/thai-break/prachathai67k] [--out data/word-weights.tsv]

The corpus (two parquet files, about 300 MB) is downloaded into --cache-dir on
first use. Titles and bodies of every article are segmented with the Python
binding in python/ and data/words.txt without weights, so the counts do not
depend on an earlier weights file. Only words of data/words.txt are counted.

The N most frequent words get weight (count / count of the N-th word) ** exponent
and every other word keeps weight 1. Weighting every word instead lets frequent
short words win over out-of-vocabulary names, which costs word F1.

License: Apache-2.0
"""

from __future__ import annotations

import argparse
import collections
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HF_BASE = "https://huggingface.co/datasets/wannaphong/prachathai67k/resolve/main/data"
SHARDS = ["train-00000-of-00002.parquet", "train-00001-of-00002.parquet"]


def fetch(cache_dir: Path, name: str) -> Path:
    path = cache_dir / name
    if not path.exists():
        cache_dir.mkdir(parents=True, exist_ok=True)
        print(f"downloading {name}", file=sys.stderr)
        tmp = path.with_suffix(".part")
        with urllib.request.urlopen(f"{HF_BASE}/{name}", timeout=300) as resp, open(tmp, "wb") as f:
            while chunk := resp.read(1 << 20):
                f.write(chunk)
        tmp.rename(path)
    return path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--top", type=int, default=3000, help="number of words that get a weight (default 3000)")
    ap.add_argument("--exponent", type=float, default=0.5, help="exponent of the count ratio (default 0.5)")
    ap.add_argument("--cache-dir", type=Path, default=Path.home() / ".cache" / "thai-break" / "prachathai67k")
    ap.add_argument("--out", type=Path, default=ROOT / "data" / "word-weights.tsv")
    args = ap.parse_args()

    import pandas as pd

    sys.path.insert(0, str(ROOT / "python"))
    import thaibreak  # type: ignore

    words_path = ROOT / "data" / "words.txt"
    if not thaibreak.init(str(words_path)):
        sys.exit("thaibreak.init() failed; build the Rust library in rust/")
    base = {line.strip() for line in words_path.read_text(encoding="utf-8").splitlines() if line.strip()}

    counts: collections.Counter[str] = collections.Counter()
    articles = 0
    for shard in SHARDS:
        df = pd.read_parquet(fetch(args.cache_dir, shard), columns=["title", "body_text"])
        for title, body in zip(df["title"], df["body_text"]):
            text = f"{title or ''} {body or ''}".strip()
            counts.update(t for t in thaibreak.words(text) if t in base)
            articles += 1
        print(f"{shard}: {articles} articles so far", file=sys.stderr)

    ranked = sorted(counts, key=lambda w: (-counts[w], w))[: args.top]
    floor = counts[ranked[-1]]
    rows = [(w, (counts[w] / floor) ** args.exponent) for w in ranked]
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(
            "# Unigram weights for the base dictionary (data/words.txt); every word not listed has weight 1.\n"
            "# Counted on Prachathai-67k (https://huggingface.co/datasets/wannaphong/prachathai67k),\n"
            "# Apache-2.0, see NOTICE. Generated by tools/build_word_weights.py:\n"
            f"# {articles} articles, the {args.top} most frequent words,"
            f" weight = (count / {floor}) ^ {args.exponent}.\n"
        )
        for w, weight in rows:
            f.write(f"{w}\t{weight:.4f}\n")
    print(f"wrote {len(rows)} weights to {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
