//! Sources of the TCC DFA tables for the Go, TypeScript and Java ports, written by
//! `thaibreak_gen_tcc` so that every port matches clusters with the DFA built from the rules in
//! `tcc.rs`.

use crate::tcc::{general_dfa_tables, lookahead_dfa_tables, DfaTables};

const HEADER: &str = "Code generated by thaibreak_gen_tcc from rust/src/tcc.rs. DO NOT EDIT.";

fn numbers<T: ToString>(values: impl IntoIterator<Item = T>, per_line: usize, indent: &str) -> String {
    let values: Vec<String> = values.into_iter().map(|v| v.to_string()).collect();
    values
        .chunks(per_line)
        .map(|chunk| format!("{indent}{},", chunk.join(", ")))
        .collect::<Vec<_>>()
        .join("\n")
}

fn go_dfa(name: &str, doc: &str, d: &DfaTables) -> String {
    format!(
        "// {doc}\nvar {name} = tccDFA{{\n\tclasses: {},\n\tstart:   {},\n\tclass: [128]uint8{{\n{}\n\t}},\n\ttrans: []uint16{{\n{}\n\t}},\n\tmatch: []bool{{\n{}\n\t}},\n}}\n",
        d.classes,
        d.start,
        numbers(d.class, 32, "\t\t"),
        numbers(&d.trans, 24, "\t\t"),
        numbers(&d.is_match, 16, "\t\t"),
    )
}

/// `go/tcc_dfa.go`
pub fn go_source() -> String {
    format!(
        "// {HEADER}\n\npackage thaibreak\n\n{}\n{}",
        go_dfa("tccGeneralDFA", "tccGeneralDFA matches the general cluster rules.", &general_dfa_tables(..)),
        go_dfa(
            "tccLookaheadDFA",
            "tccLookaheadDFA matches the lookahead rules (-ีย before a syllable start).",
            &lookahead_dfa_tables()
        ),
    )
}

fn ts_dfa(name: &str, doc: &str, d: &DfaTables) -> String {
    format!(
        "/** {doc} */\nexport const {name}: TccDfaTables = {{\n  classes: {},\n  start: {},\n  class: [\n{}\n  ],\n  trans: [\n{}\n  ],\n  match: [\n{}\n  ],\n}};\n",
        d.classes,
        d.start,
        numbers(d.class, 32, "    "),
        numbers(&d.trans, 24, "    "),
        numbers(d.is_match.iter().map(|&m| u8::from(m)), 32, "    "),
    )
}

/// `typescript/src/tcc_dfa.ts`
pub fn typescript_source() -> String {
    format!(
        "// {HEADER}\n\n/** Tables of an anchored leftmost-first DFA over classes of U+0E00..U+0E7F. */\nexport interface TccDfaTables {{\n  classes: number;\n  start: number;\n  /** class of each character of the Thai block */\n  class: number[];\n  /** next state at state * classes + class, state 0 is dead */\n  trans: number[];\n  /** 1 for a matching state */\n  match: number[];\n}}\n\n{}\n{}",
        ts_dfa("TCC_DFA_GENERAL", "The general cluster rules.", &general_dfa_tables(..)),
        ts_dfa(
            "TCC_DFA_LOOKAHEAD",
            "The lookahead rules (-ีย before a syllable start).",
            &lookahead_dfa_tables()
        ),
    )
}

/// Values below 0x10000 as a Java string literal, split over several lines. Small values are octal
/// escapes: Java turns `"` and `\u000a` into a quote and a line break before it reads the
/// literal.
fn java_chars(values: impl IntoIterator<Item = u16>) -> String {
    let escaped: Vec<String> = values
        .into_iter()
        .map(|v| if v < 0x100 { format!("\\{v:03o}") } else { format!("\\u{v:04x}") })
        .collect();
    escaped
        .chunks(16)
        .map(|chunk| format!("            \"{}\"", chunk.concat()))
        .collect::<Vec<_>>()
        .join(" +\n")
}

fn java_dfa(name: &str, doc: &str, d: &DfaTables) -> String {
    format!(
        "    /** {doc} */\n    static final ThaiTccDfa {name} = new ThaiTccDfa(\n        {},\n        {},\n{},\n{},\n{}\n    );\n",
        d.classes,
        d.start,
        java_chars(d.class.iter().map(|&c| u16::from(c))),
        java_chars(d.trans.iter().copied()),
        java_chars(d.is_match.iter().map(|&m| u16::from(m))),
    )
}

